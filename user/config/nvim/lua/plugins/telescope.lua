return {
  {
    "nvim-telescope/telescope.nvim",
    dependencies = {
      "nvim-telescope/telescope-fzf-native.nvim",
      "nvim-lua/plenary.nvim",
      "folke/noice.nvim",
      {
        "nvim-telescope/telescope-ui-select.nvim",
        config = function()
          require("telescope").setup({
            extensions = {
              ["ui-select"] = {
                require("telescope.themes").get_dropdown({}),
              },
            },
          })
          require("telescope").load_extension("ui-select")
        end,
      },
      { "nvim-tree/nvim-web-devicons", enabled = true },
    },
    config = function()
      local telescopeConfig = require("telescope.config")

      local vimgrep_arguments = { telescopeConfig.values.vimgrep_arguments }
      table.insert(vimgrep_arguments, "--hidden")

      require("telescope").setup({
        defaults = {
          file_ignore_patterns = {
            "^node_modules/",
            "^.git/",
          },
        },
        pickers = {
          find_files = {
            find_command = { "rg", "--files", "--hidden" },
          },
        },
        extensions = {
          ["ui-select"] = {
            require("telescope.themes").get_dropdown(),
          },
        },
      })
      pcall(require("telescope").load_extension, "fzf")
      pcall(require("telescope").load_extension, "ui-select")
      pcall(require("telescope").load_extension, "noice")
      local builtin = require("telescope.builtin")
      vim.keymap.set("n", "<leader>ff", builtin.find_files, { desc = "[F]ind [F]iles" })
      vim.keymap.set("n", "<leader>fb", builtin.buffers, { desc = "[F]earch [B]uffers" })
      vim.keymap.set("n", "<leader>fg", builtin.live_grep, { desc = "[F]ind by [G]rep" })
      vim.keymap.set("n", "<leader>fh", builtin.help_tags, { desc = "[F]ind [H]elp" })
      vim.keymap.set("n", "<leader>fk", builtin.keymaps, { desc = "[F]ind [K]eymaps" })
      vim.keymap.set("n", "<leader>fs", builtin.builtin, { desc = "[F]ind [S]elect Telescope" })
      vim.keymap.set("n", "<leader>fw", builtin.grep_string, { desc = "[F]ind current [W]ord" })
      vim.keymap.set("n", "<leader>fm", "<cmd>Telescope noice<CR>", { desc = "[F]ind [N]oice" })
      vim.keymap.set("n", "<leader>fl", "<cmd>Telescope notify<CR>", { desc = "[F]ind Notifications" })
      vim.keymap.set("n", "<leader>fn", function()
        builtin.find_files({ cwd = vim.fn.stdpath("config") })
      end, { desc = "[F]ind [N]eovim files" })
    end,
  },
}
